import json


def read_events(lines):
    """Read complete SSE events from decoded HTTP lines; ignore comment heartbeats."""
    event, data = "message", []
    for line in lines:
        if line == "":
            if data:
                yield event, json.loads("\n".join(data))
            event, data = "message", []
        elif not line.startswith(":"):
            field, _, value = line.partition(":")
            value = value.removeprefix(" ")
            if field == "event":
                event = value
            elif field == "data":
                data.append(value)
    # An event without its terminating blank line is incomplete and not delivered.
